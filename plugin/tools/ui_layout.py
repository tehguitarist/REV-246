#!/usr/bin/env python3
"""Reads plugin/ui-layout.csv and either writes src/ui/Layout.h or prints the asset size list.

    .venv/bin/python plugin/tools/ui_layout.py header   # regenerate src/ui/Layout.h
    .venv/bin/python plugin/tools/ui_layout.py assets   # "<file> <width> <height>" per image, for build_assets.sh

ui-layout.csv is the cleaned version of ui/Asset positioning.csv (the designer's notes): x/y are slot CENTRES in the
3495x1530 design space (main.png's 3495x1380 plus the 150-high bottom bar drawn in code), so a display box given there
by its top-left corner is already converted. A row without a file is a slot only (display boxes, level LEDs).
Behaviour that the sheet describes in words (fader travel, funnel geometry) lives in src/ui/Design.h.

Adding a control: add its rows, run tools/build_assets.sh, then use the generated slot in the editor.
"""

import csv
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "ui-layout.csv"
HEADER_PATH = ROOT / "src" / "ui" / "Layout.h"

DESIGN_W, DESIGN_H = 3495, 1530
ASSET_SCALE = 1.0  # assets ship 1:1 with the design space (2.5x the 1398-wide default editor)


def camel(name: str) -> str:
    words = name.replace("-", " ").split()
    return words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])


def read_rows():
    with open(CSV_PATH, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def build():
    slots = OrderedDict()   # component -> (cx, cy, w, h)
    images = OrderedDict()  # file -> max slot (w, h)
    for r in read_rows():
        slot = tuple(float(r[k]) for k in ("x", "y", "w", "h"))
        name = camel(r["component"])
        if name in slots and slots[name] != slot:
            sys.exit(f"ui-layout.csv: rows for '{r['component']}' disagree on position or size")
        slots[name] = slot
        if r["file"]:
            pw, ph = images.get(r["file"], (0, 0))
            images[r["file"]] = (max(pw, slot[2]), max(ph, slot[3]))
    return slots, images


def f(v):
    return f"{v:g}.0f" if float(v).is_integer() else f"{v:g}f"


def write_header(slots, images):
    lines = [
        "// Generated by tools/ui_layout.py from ui-layout.csv. Do not edit by hand: change the CSV and run",
        "// tools/build_assets.sh. Slots are centre + size in the 3495x1530 design space.",
        "#pragma once",
        "",
        "#include <juce_graphics/juce_graphics.h>",
        "",
        "#include <iterator>",
        "",
        "namespace rv::layout",
        "{",
        f"inline constexpr float designWidth = {f(DESIGN_W)};",
        f"inline constexpr float designHeight = {f(DESIGN_H)};",
        "",
        "struct Slot",
        "{",
        "    float cx, cy, w, h;",
        "",
        "    juce::Rectangle<float> bounds() const { return { cx - w * 0.5f, cy - h * 0.5f, w, h }; }",
        "};",
        "",
    ]
    width = max(len(n) for n in slots)
    for name, (cx, cy, w, h) in slots.items():
        lines.append(f"inline constexpr Slot {name:<{width}} {{ {f(cx)}, {f(cy)}, {f(w)}, {f(h)} }};")
    lines += ["", "// Every embedded image, by its file name in ui/ (and assets/images/).", "enum class Image", "{"]
    lines += [f"    {camel(n)}," for n in images]
    lines += ["    count", "};", "", "inline constexpr const char* imageFileNames[] = {"]
    lines += [f'    "{n}.png",' for n in images]
    lines += ["};", "", "static_assert (std::size (imageFileNames) == (size_t) Image::count);", "} // namespace rv::layout", ""]
    HEADER_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {HEADER_PATH.relative_to(ROOT)} ({len(slots)} slots, {len(images)} images)")


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("header", "assets"):
        sys.exit(__doc__)
    slots, images = build()
    if sys.argv[1] == "header":
        write_header(slots, images)
    else:
        for name, (w, h) in images.items():
            print(f"{name}\t{round(w * ASSET_SCALE)}\t{round(h * ASSET_SCALE)}")


if __name__ == "__main__":
    main()
