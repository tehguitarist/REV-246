"""Generator for plugin/src/presets/FactoryPresets.h: the Altiverb EMT 246 presets as factory presets, from
analysis/altiverb/presets.json (tools/altiverb_presets.py; method in docs/library_notes.md section 7).

    .venv/bin/python -m tools.plugin_codegen.presets

One row per preset the plugin can play (S / M / L / E / N): its name, program and a step index per joystick in
rv::params::Joy order (lowpass, delay, ampl, lf, rt, hf), plus a short label of the inferred settings with their
confidence (C confirmed, S strong, H hypothesis). Presets of programs the plugin does not have (the delay / echo
program) are left out. The header is committed so the plugin builds without Python.
"""
import json
import re
import textwrap

from .common import ROOT

SRC = "analysis/altiverb/presets.json"
OUT = ROOT / "plugin" / "src" / "presets" / "FactoryPresets.h"
PROGRAMS = ["S", "M", "L", "E", "N"]          # rv::params::Program order: s, m, l, e, n
JOYS = ["lowpass", "delay", "ampl", "lf", "rt", "hf"]   # rv::params::Joy order
MAX_STEP = {"lowpass": 7, "delay": 999, "ampl": 10, "lf": 15, "rt": 15, "hf": 10}   # joyMaxStep(Joy)
FAMILY_ORDER = ["NON-LIN SHORT RT", "MED RT", "LONG RT", "REV-250", "NON-LIN"]


def order(name):
    """Families first (S, M, L, E by RT, then N), then the numbered presets by number."""
    m = re.match(r"PRESET(\d+)", name)
    if m:
        return (1, int(m.group(1)), 0.0)
    for i, f in enumerate(FAMILY_ORDER):
        if name == f or name.startswith(f + " "):
            rt = re.search(r"([\d.]+)s$", name)
            return (0, i, float(rt.group(1)) if rt else 0.0)
    return (2, 0, 0.0)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = json.loads((ROOT / SRC).read_text())
    rows, skipped = [], []
    for name in sorted(data["presets"], key=order):
        e = data["presets"][name]
        if not e.get("included"):
            skipped.append(f"{name}: {e.get('why_not', 'not a plugin program')}")
            continue
        steps = []
        for j in JOYS:
            st = int(e["settings"][j]["step"])
            assert 0 <= st <= MAX_STEP[j], (name, j, st)
            steps.append(st)
        assert len(e["plugin_name"]) <= 24, e["plugin_name"]
        rows.append((e["plugin_name"], PROGRAMS.index(e["program"]), steps, e["label_string"], name))
    names = [r[0] for r in rows]
    assert len(set(names)) == len(names), "duplicate preset names"

    body = []
    for nm, prog, steps, label, src in rows:
        body.append(f"    FactoryPreset{{{cstr(nm)}, {prog}, {{{{{', '.join(map(str, steps))}}}}},\n"
                    f"                  {cstr(label)},\n                  {cstr(src)}}},")
    text = "\n".join([
        "#pragma once",
        "",
        f"// GENERATED by tools/plugin_codegen/presets.py from {SRC}. Do not edit; rerun the generator.",
        "//",
        "// The Altiverb EMT 246 presets as factory presets: best-guess front-panel settings read from each preset's IR",
        "// (tools/altiverb_presets.py; method and table in docs/library_notes.md section 7). Labels: C confirmed,",
        "// S strong (several measurements agree), H hypothesis.",
        "//",
        "// program: (int) rv::params::Program (0 s, 1 m, 2 l, 3 e, 4 n).",
        "// steps:   one step index per joystick in rv::params::Joy order: lowpass, delay, ampl, lf, rt, hf (the indices",
        "//          joyValue / joyNumber take; N: ampl = SPAN, lf = EARLY RT, hf = LATE RT, rt unused at the default step).",
        "// label:   the settings as read, with their confidence.",
        "// source:  the Altiverb preset's name.",
        "//",
        "// Left out (not one of the plugin's programs):",
        *[ln for sk in skipped for ln in textwrap.wrap(sk, 112, initial_indent="//   ", subsequent_indent="//     ")],
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace rv::presets",
        "{",
        "inline constexpr int factoryJoyCount = 6; // rv::params::numJoys",
        "",
        "struct FactoryPreset",
        "{",
        "    const char* name;",
        "    int program;",
        "    std::array<int, factoryJoyCount> steps;",
        "    const char* label;",
        "    const char* source;",
        "};",
        "",
        f"inline constexpr std::array<FactoryPreset, {len(rows)}> factoryPresets{{{{",
        *body,
        "}};",
        "} // namespace rv::presets",
        "",
    ])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} presets, {len(skipped)} left out")


if __name__ == "__main__":
    main()
