"""Shared helpers for the spec -> C++ generators (plugin/docs/ENGINE.md, Generated data).

Each program has its own module here (s.py, ml.py, e.py, n.py) that reads its spec JSON and writes
plugin/src/dsp/generated/<prog>_spec.h through `Header`. Numbers are written with repr(), which round-trips a
double exactly, so the C++ tables equal the spec's values bit for bit. Run a generator as
`.venv/bin/python -m tools.plugin_codegen.<prog>` from the repository root; the headers are committed so the plugin
builds without Python.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "plugin" / "src" / "dsp" / "generated"


def load(rel):
    return json.loads((ROOT / rel).read_text())


def num(x):
    """One double literal that round-trips exactly."""
    r = repr(float(x))
    return r if any(c in r for c in ".eEn") else r + ".0"


class Header:
    """Collects constexpr declarations and writes them as one header in namespace rv::dsp::gen::<ns>."""

    def __init__(self, ns, source):
        self.ns, self.source, self.lines = ns, source, []

    def comment(self, text):
        self.lines += [f"// {t}" for t in text.splitlines()]

    def scalar(self, name, value, ctype="double"):
        v = num(value) if ctype in ("double", "float") else str(int(value))
        self.lines.append(f"inline constexpr {ctype} {name} = {v};")

    def array(self, name, values, ctype="double", per_line=4):
        vals = [num(v) if ctype in ("double", "float") else str(int(v)) for v in values]
        rows = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)] or [""]
        body = ",\n    ".join(rows)
        self.lines.append(f"inline constexpr std::array<{ctype}, {len(vals)}> {name}{{{{\n    {body}}}}};")

    def raw(self, text):
        self.lines += text.splitlines()

    def write(self, filename):
        text = "\n".join([
            "#pragma once",
            "",
            f"// GENERATED by tools/plugin_codegen from {self.source}. Do not edit; rerun the generator.",
            "",
            "#include <array>",
            "#include <cstdint>",
            "",
            f"namespace rv::dsp::gen::{self.ns}",
            "{",
            *self.lines,
            f"}} // namespace rv::dsp::gen::{self.ns}",
            "",
        ])
        OUT.mkdir(parents=True, exist_ok=True)
        (OUT / filename).write_text(text)
        return OUT / filename
