"""IR vs REV-246 on real sources: how alike are the two wets that tools/ab_samples.py made?

    .venv/bin/python -I tools/ab_analysis.py     -> analysis/ab_samples/report.md

Both wets are the same input convolved / rendered, level-matched in RMS. Per example and per 1/3-octave band
(31.5 Hz - 12.5 kHz):
  * null  : residual of IR wet after the least-squares gain onto the plugin wet, re the IR wet (dB, lower = closer);
  * level : band RMS of IR wet minus plugin wet (dB), over the whole render;
  * env   : RMS difference of the two level-vs-time curves (250 ms bins, dB, each band), IR - plugin.
Time-variant programs (M, N) also get a reference: the plugin rendered twice with the time variance at another phase
(pre=0.37 s) and nulled the same way, i.e. how far apart two plugin 'captures' of one setting are.
"""
import json, subprocess
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.optimize import minimize
from scipy.signal import butter, fftconvolve, resample_poly, sosfiltfilt

ROOT = Path(__file__).resolve().parent.parent
W = ROOT / "analysis/ab_samples"
RATE = 48000
BANDS = [31.5 * 2 ** (i / 3) for i in range(0, 26)]
BANDS = [f for f in BANDS if f <= 12600]


def band(x, fc):
    lo, hi = fc / 2 ** (1 / 6), min(fc * 2 ** (1 / 6), 0.45 * RATE)
    sos = butter(4, [lo, hi], btype="band", fs=RATE, output="sos")
    return sosfiltfilt(sos, x, axis=0)


def null_db(a, b):
    g = float(np.sum(a * b) / np.sum(b * b))
    return 10 * np.log10(np.sum((a - g * b) ** 2) / np.sum(a ** 2)), 20 * np.log10(abs(g))


def env(x, n=int(0.25 * RATE)):
    k = len(x) // n
    return 10 * np.log10(np.mean(x[:k * n].reshape(k, n) ** 2, axis=1) + 1e-20)


def analyse(a, b, active):
    """a = IR wet, b = plugin wet (stereo arrays); active = number of bins where the env comparison is meaningful."""
    rows = []
    for fc in BANDS:
        A, B = band(a, fc), band(b, fc)
        n, _ = null_db(A, B)
        lvl = 10 * np.log10(np.mean(A ** 2) / np.mean(B ** 2))
        ea, eb = env(A[:, 0])[:active], env(B[:, 0])[:active]
        ok = (ea > -100) & (eb > -100)  # both above -100 dB: past an IR's fade or end the comparison is empty
        e = (ea - eb)[ok]
        rows.append((fc, n, lvl, float(np.sqrt(np.mean(e ** 2)))))
    return rows


def warped_wet(mono, k8, eps, d, n_out):
    """The IR convolved with the source, the IR's clock ratio (1 + eps) and a fractional delay d (samples) applied to it."""
    n = (len(k8) // 8)
    t = (np.arange(n) * (1 + eps) - d) * 8
    k = np.stack([np.interp(t, np.arange(len(k8)), k8[:, c], left=0, right=0) for c in range(2)], axis=1)
    w = np.stack([fftconvolve(mono, k[:, c]) for c in range(2)], axis=1)
    return np.pad(w, ((0, max(0, n_out - len(w))), (0, 0)))[:n_out]


def clock_fit(mono, kernel, gain, pl):
    """Fit the IR's clock ratio and fractional delay (2 numbers) so its wet best nulls the plugin's, 100 Hz - 4 kHz.
    Two captures of one unit setting agree only after such a fit (docs/NEXT_STEPS.md: clock ratio fitted per capture)."""
    k8 = resample_poly(kernel, 8, 1, axis=0)
    sos = butter(4, [100, 4000], btype="band", fs=RATE, output="sos")
    pb = sosfiltfilt(sos, pl, axis=0)

    def cost(v):
        if abs(v[0]) > 150 or abs(v[1]) > 1.0:  # the units' clocks differ by up to ~100 ppm (crystal tolerance): keep the fit physical
            return 0.0
        w = warped_wet(mono, k8, v[0] * 1e-6, v[1], len(pl))
        a = sosfiltfilt(sos, w, axis=0)
        return null_db(a, pb)[0]

    best = min(((cost([0, d]), d) for d in (-0.5, -0.25, 0, 0.25, 0.5)))
    r = minimize(cost, [0.0, best[1]], method="Nelder-Mead", options=dict(initial_simplex=[[0, best[1]], [15, best[1]], [0, best[1] + 0.3]], xatol=0.02, fatol=0.01, maxiter=80))
    w = warped_wet(mono, k8, r.x[0] * 1e-6, r.x[1], len(pl))
    return w * gain, r.x

def render_ref(name, ex_args, n_out):
    out = W / f"{name}_ref_raw.wav"
    cmd = [str(ROOT / "plugin/build-render/REV246Render_artefacts/Release/REV246Render"), f"out={out}", f"rate={RATE}",
           f"len={n_out / RATE + 0.5:.4f}", "pre=0.37", "mod=1"] + ex_args
    line = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout.strip().splitlines()[-1]
    lat = int(line.split("latency=")[1].split()[0])
    y, _ = sf.read(out, always_2d=True)
    return y[lat:lat + n_out, :2]


def main():
    ex_lookup = {e["name"]: e for e in __import__("importlib").import_module("ab_samples").EXAMPLES}
    lines = ["# IR vs REV-246 on real sources", "", "Generated by `tools/ab_analysis.py` from the wets of `tools/ab_samples.py` "
             "(RMS-matched, 48 kHz, plugin latency removed). null = residual after best gain re the IR wet; level and env "
             "are IR minus plugin. **Not held-out evidence of the algorithm**: they only show how alike the two wets sound.", ""]
    lines += ["## Reading (31 October 2026 run; written by hand, rerun the tool for the tables)", "",
              "- **Levels and decay shapes match everywhere.** Per 1/3-octave band, IR minus plugin level is within 0.4 dB (room mic), "
              "0.0 dB (guitar), 1.5 dB (gated snare, Altiverb) and 2.4 dB (piano; the IR is 1.5-2.7 dB darker above 6 kHz), and the "
              "250 ms level-vs-time curves agree to 0.0-1.6 dB rms per band.",
              "- **Programme S on a Tomkin IR (guitar) nulls -42.9 dB broadband, -43 dB median band, on a real source** "
              "(2 fitted numbers: clock +9.6 ppm, delay +0.03 samples). That is the bench's late-window level (-46 / -41 dB at 150-300 / "
              "300-600 ms), as expected: a whole recording integrates all windows.",
              "- **N on a Tomkin IR (snare, DELAY 0): -27 dB broadband, -35 dB median band** (-41 dB at 100-400 Hz); the Altiverb gated "
              "preset: -17 dB. The plugin's N is not time-varying (itself at another phase: -55 dB), so the gap to the Altiverb "
              "is that capture and the preset-setting guess (DELAY 39 is H), not modulation.",
              "- **S on the CLA IR (room mic): -20 dB broadband**, best (-49 dB) at 800 Hz and falling away both sides while the levels "
              "match to 0.4 dB: a phase / transfer difference between that unit's capture chain and the plugin, not the reverb "
              "(H; the fit wants +98 ppm, outside the Tomkin unit's 12.6 ppm). Below 100 Hz the plugin lacks the unit's measured low-band "
              "transfer, which the render tool does not include.",
              "- **M on the Altiverb IR (piano): -15 dB, against -19 dB for the plugin vs itself at another time-variance phase.** The IR is "
              "as far from the plugin as two plugin renders are from each other (about 3.5 dB apart), so waveform nulls are the wrong "
              "measure here; the levels and envelopes above are.",
              "- Not held-out in the sense of the research gates: the settings and the 2-number fit are chosen on the same recording. "
              "These numbers show how alike the wets sound, not that the algorithm is the unit's.", ""]
    summary = {}
    for name in ["room-mic", "piano", "acoustic-guitar", "snare-ir2", "snare-ir3"]:
        z = np.load(W / f"{name}_wets.npz")
        ir, pl = z["ir"].astype(float), z["plugin"].astype(float)
        mono = sf.read(W / f"{name}_mono.wav")[0]
        ir0 = ir
        ir, (ppm, dly) = clock_fit(mono, z["kernel"].astype(float), float(z["gain"]), pl)
        ir *= np.sqrt(np.mean(pl ** 2) / np.mean(ir ** 2))
        ex = ex_lookup[name]
        src = sf.read(ROOT / "ref" / f"{ex['wav']}.wav", always_2d=True)[0]
        active = int(len(src) / RATE / 0.25) + int(ex["tail"] / 0.25) - 2
        rows = analyse(ir, pl, active)
        ref_rows = None
        if ex["prog"] in "MN":
            args = [f"program={ex['prog']}", f"input={W / (name + '_mono.wav')}"] + [f"{k}={v}" for k, v in ex["args"].items()]
            r = render_ref(name, args, len(pl))
            r = r * (np.sqrt(np.mean(pl ** 2)) / np.sqrt(np.mean(r ** 2)))
            ref_rows = analyse(r, pl, active)
        full, g = null_db(ir, pl)
        lines += [f"## {name} (IR source {ex['src']}): {ex['text']}", "",
                  f"Fit on the IR (2 numbers, 100 Hz - 4 kHz): clock {ppm:+.1f} ppm, delay {dly:+.2f} samples; broadband null "
                  f"{null_db(ir0, pl)[0]:.1f} dB before, {full:.1f} dB after (gain {g:+.1f} dB)."
                  + (f" Plugin vs itself at another time-variance phase: {null_db(r, pl)[0]:.1f} dB." if ref_rows else ""), "",
                  "| band Hz | null dB | level dB | env rms dB |" + (" ref null dB | ref env dB |" if ref_rows else ""),
                  "|---|---|---|---|" + ("---|---|" if ref_rows else "")]
        for i, (fc, n, lv, en) in enumerate(rows):
            s = f"| {fc:.0f} | {n:.1f} | {lv:+.1f} | {en:.1f} |"
            if ref_rows:
                s += f" {ref_rows[i][1]:.1f} | {ref_rows[i][3]:.1f} |"
            lines.append(s)
        mid = [r for r in rows if 100 <= r[0] <= 10000]
        summary[name] = dict(broadband_null=full, band_null_median=float(np.median([r[1] for r in mid])),
                             level_abs_max=float(max(abs(r[2]) for r in mid)), env_rms_median=float(np.median([r[3] for r in mid])))
        lines.append("")
    (W / "report.md").write_text("\n".join(lines))
    (W / "summary.json").write_text(json.dumps(summary, indent=1))
    for k, v in summary.items():
        print(k, {a: round(b, 1) for a, b in v.items()})


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(ROOT / "tools"))
    main()
